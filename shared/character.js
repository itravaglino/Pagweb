function weekSlice(payloads, date) {
  const idx = payloads.findIndex((p) => p.date === date);
  if (idx < 0) return [];
  const start = idx - (idx % 7);
  return payloads.slice(start, start + 7).map((p) => ({
    date: p.date,
    persona: p.kind,
    label: p.weekday,
    steps: p.activity.summary.steps,
    sleepMinutes: p.sleep.summary.totalMinutesAsleep,
    hrv: p.hrv.dailyRmssd,
    rhr: p.heart.restingHeartRate,
    calories: p.activity.summary.caloriesOut,
  }));
}

let cached = null;

function buildAll() {
  if (cached) return cached;
  const payloads = RECIPES.map((recipe) => pack(recipe));
  for (const payload of payloads) {
    payload.week = weekSlice(payloads, payload.date);
  }
  cached = payloads;
  return cached;
}

export function allCharacterPayloads() {
  return buildAll();
}

export function hasCharacterDate(date) {
  return buildAll().some((p) => p.date === date);
}

export function getCharacterPayload(date = CHARACTER_TO) {
  return buildAll().find((p) => p.date === date) || buildAll().at(-1);
}

export function publicIdentity() {
  return { ...CHARACTER, from: CHARACTER_FROM, to: CHARACTER_TO };
}

function dayRecord(payload) {
  const metrics = toMetrics(payload);
  metrics.log = payload.log;
  metrics.kind = payload.kind;
  metrics.weekday = payload.weekday;
  return {
    date: payload.date,
    weekday: payload.weekday,
    kind: payload.kind,
    log: payload.log,
    metrics,
  };
}

export function listCharacterDays() {
  return buildAll().map(dayRecord);
}

function metGoal(metrics) {
  return (metrics.steps || 0) >= CHARACTER.goal.steps && (metrics.sleepMinutes || 0) >= 420;
}

export function getCharacterSummary() {
  const days = listCharacterDays();
  const n = days.length || 1;
  const sum = (fn) => days.reduce((a, d) => a + (fn(d.metrics) || 0), 0);
  const weeks = [];
  for (let i = 0; i < days.length; i += 7) {
    const slice = days.slice(i, i + 7);
    weeks.push({
      from: slice[0]?.date,
      to: slice.at(-1)?.date,
      label: `Semana ${weeks.length + 1}`,
      steps: slice.reduce((a, d) => a + d.metrics.steps, 0),
      avgSteps: Math.round(slice.reduce((a, d) => a + d.metrics.steps, 0) / slice.length),
      avgSleep: Math.round(slice.reduce((a, d) => a + d.metrics.sleepMinutes, 0) / slice.length),
      avgHrv: Math.round(slice.reduce((a, d) => a + (d.metrics.hrvRmssd || 0), 0) / slice.length),
      days: slice.map((d) => ({
        date: d.date,
        weekday: d.weekday,
        kind: d.kind,
        steps: d.metrics.steps,
        sleepMinutes: d.metrics.sleepMinutes,
        hrv: d.metrics.hrvRmssd,
      })),
    });
  }
  let streak = 0;
  for (let i = days.length - 1; i >= 0; i -= 1) {
    if (metGoal(days[i].metrics)) streak += 1;
    else break;
  }
  const last = days.at(-1);
  return {
    days: n,
    from: CHARACTER_FROM,
    to: CHARACTER_TO,
    avgSteps: Math.round(sum((m) => m.steps) / n),
    avgSleepMinutes: Math.round(sum((m) => m.sleepMinutes) / n),
    avgHrv: Math.round(sum((m) => m.hrvRmssd) / n),
    avgRhr: Math.round(sum((m) => m.restingHeartRate) / n),
    totalSteps: sum((m) => m.steps),
    gymDays: days.filter((d) => d.kind === "gym" || d.kind === "futbol").length,
    streak,
    lastNight: {
      date: last.date,
      sleepMinutes: last.metrics.sleepMinutes,
      steps: last.metrics.steps,
      hrv: last.metrics.hrvRmssd,
      rhr: last.metrics.restingHeartRate,
    },
    thisWeek: weeks[3] || weeks.at(-1),
    lastWeek: weeks[2] || weeks.at(-2),
    weeks,
  };
}

